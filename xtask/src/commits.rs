//! Conventional Commits validation (<https://www.conventionalcommits.org>).
//!
//! Squash merges use the pull request title as the commit message, so CI applies the same
//! rule to PR titles. Changelogs are generated from these messages (`cliff.toml`).

use std::path::Path;

use crate::util::Result;

/// Allowed commit types and their changelog section (see `cliff.toml`).
pub(crate) const TYPES: [&str; 11] = [
    "feat", "fix", "perf", "refactor", "test", "docs", "build", "ci", "chore", "revert", "style",
];

const MAX_HEADER_LEN: usize = 100;

const FORMAT: &str = "\
expected `<type>(<optional scope>)!: <description>`, for example:
  feat(render): add rounded rectangle borders
  fix(gpu)!: recreate the swapchain on VK_SUBOPTIMAL_KHR
types: feat fix perf refactor test docs build ci chore revert style";

/// Validates the first line of a commit message.
pub(crate) fn check_header(header: &str) -> Result<()> {
    // Messages generated by git itself are accepted as-is.
    if ["Merge ", "Revert \"", "fixup! ", "squash! ", "amend! "]
        .iter()
        .any(|p| header.starts_with(p))
    {
        return Ok(());
    }
    let fail = |reason: &str| Err(format!("{reason}: {header:?}\n{FORMAT}").into());
    if header.chars().count() > MAX_HEADER_LEN {
        return fail(&format!("header longer than {MAX_HEADER_LEN} characters"));
    }
    let Some((prefix, description)) = header.split_once(": ") else {
        return fail("missing `: ` after the type");
    };
    let prefix = prefix.strip_suffix('!').unwrap_or(prefix);
    let (kind, scope) = match prefix.split_once('(') {
        Some((kind, rest)) => match rest.strip_suffix(')') {
            Some(scope) => (kind, Some(scope)),
            None => return fail("unclosed scope parenthesis"),
        },
        None => (prefix, None),
    };
    if !TYPES.contains(&kind) {
        return fail(&format!("unknown type {kind:?}"));
    }
    if let Some(scope) = scope
        && (scope.is_empty()
            || !scope
                .chars()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '-'))
    {
        return fail("scope must be lowercase letters, digits or '-'");
    }
    let description = description.trim();
    if description.is_empty() {
        return fail("empty description");
    }
    if description.ends_with('.') {
        return fail("description must not end with a period");
    }
    Ok(())
}

/// Validates a commit message file (used by the `commit-msg` git hook).
pub(crate) fn check_message_file(path: &Path) -> Result<()> {
    let message = std::fs::read_to_string(path)?;
    let header = message
        .lines()
        .map(str::trim_end)
        .find(|line| !line.is_empty() && !line.starts_with('#'))
        .ok_or("empty commit message")?;
    check_header(header)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn conventional_headers_are_accepted() {
        for header in [
            "feat: add scene clearing",
            "feat(render): add rounded rectangle borders",
            "fix(gpu)!: recreate the swapchain when suboptimal",
            "ci(github-actions): pin actions by SHA",
            "chore(release): 0.2.0",
            "Merge branch 'main' into develop",
            "fixup! feat: add scene clearing",
        ] {
            assert!(check_header(header).is_ok(), "{header}");
        }
    }

    #[test]
    fn malformed_headers_are_rejected() {
        for header in [
            "add scene clearing",
            "feature: add scene clearing",
            "feat(Render): x",
            "feat(): x",
            "feat(render: x",
            "feat: ",
            "feat: add scene clearing.",
            &format!("feat: {}", "x".repeat(120)),
        ] {
            assert!(check_header(header).is_err(), "{header}");
        }
    }
}
