//! The palettes of the built-in themes: every step keeps its contrast with its theme's
//! background (`koebi_tokens::palettes`).
//!
//! `KOEBI_BLESS=1 cargo nextest run -p koebi-tokens palettes` writes the palettes again from
//! their keys: the hue table (`src/primitive/palette.rs`, the dark base theme's), the grays of
//! `src/primitive/neutral.rs`, and the `values` block of each theme that changes them. Without
//! it, the test checks the values as they are, so that a value tuned by hand stays within its
//! step's tolerance.

use std::fmt::Write as _;
use std::path::Path;

use koebi_core::Color;
use koebi_core::palette::HUE_STEPS;
use koebi_design::DesignSystem;
use koebi_tokens::KOEBI;
use koebi_tokens::palettes::{
    HUES, LAST_HUE_FILL, LAST_NEUTRAL_FILL, NEUTRAL_STEPS, Scheme, THEMES, ThemePalettes,
};

/// How far a step's contrast may stray from its target, as a share of it.
const TOLERANCE: f32 = 0.04;

const GENERATED: &str =
    "// Generated by tests/palettes.rs (KOEBI_BLESS=1) from `koebi_tokens::palettes`.";
const END: &str = "// End of the generated palettes.";

fn hex(color: Color) -> String {
    color.to_string().to_uppercase()
}

fn title(name: &str) -> String {
    let mut chars = name.chars();
    chars.next().map_or_else(String::new, |first| {
        first.to_uppercase().chain(chars).collect()
    })
}

fn root() -> &'static Path {
    Path::new(env!("CARGO_MANIFEST_DIR"))
}

/// The hue table of the base theme, the whole file.
fn palette_table(base: &ThemePalettes) -> String {
    let contrasts = base.hue_contrasts();
    let mut out = String::from(
        "//! Hue palettes: 18 hues in 16 steps, ordered by contrast with the window's background:\n\
         //! step 100 the closest to it, 1600 the farthest. The values are the dark base theme's;\n\
         //! every other theme gives each step the color that keeps its contrast against its own\n\
         //! background (`crate::palettes`).\n\nuse koebi_design::define::*;\n\n\
         koebi_design::tokens! {\n    group PALETTE: Primitive, start = 0;\n\n",
    );
    writeln!(out, "    {GENERATED}").expect("writing to a String never fails");
    for hue in HUES {
        let steps = base.hue(hue.name).expect("a known hue");
        for ((step, color), ratio) in HUE_STEPS.iter().zip(steps).zip(contrasts) {
            writeln!(
                out,
                "    /// {}, step {step}: {ratio}:1 against the background.\n    COLOR_{}_{step} = \"color.{}.{step}\": Color = hex(\"{}\");",
                title(hue.name),
                hue.name.to_uppercase(),
                hue.name,
                hex(color),
            )
            .expect("writing to a String never fails");
        }
        writeln!(
            out,
            "    /// {}: the color its palette is made from, its step 900 until the color settings\n    /// make it from another (`crate::palettes::Editable`).\n    COLOR_{}_SOURCE = \"color.{}.source\": Color = hex(\"{}\");",
            title(hue.name),
            hue.name.to_uppercase(),
            hue.name,
            hex(steps[8]),
        )
        .expect("writing to a String never fails");
    }
    writeln!(out, "    {END}\n}}").expect("writing to a String never fails");
    out
}

/// The grays of the base theme, as token definitions.
fn gray_definitions(base: &ThemePalettes) -> String {
    let mut out = String::new();
    for (index, (step, color)) in NEUTRAL_STEPS.iter().zip(base.neutral()).enumerate() {
        let what = match index {
            0 => "the deepest surface".to_owned(),
            1 => "the window's background".to_owned(),
            15 => "the end of the scale".to_owned(),
            _ => format!("{}:1 against the background", base.neutral_contrasts[index]),
        };
        writeln!(
            out,
            "    /// Gray, step {step}: {what}.\n    COLOR_GRAY_{step} = \"color.gray.{step}\": Color = hex(\"{}\");",
            hex(color)
        )
        .expect("writing to a String never fails");
    }
    out
}

/// A theme's `values` entries: its grays and its hues.
fn theme_values(theme: &ThemePalettes) -> String {
    let mut out = String::new();
    for (step, color) in NEUTRAL_STEPS.iter().zip(theme.neutral()) {
        writeln!(
            out,
            "            primitive::COLOR_GRAY_{step}: Color = hex(\"{}\");",
            hex(color)
        )
        .expect("writing to a String never fails");
    }
    for hue in HUES {
        let steps = theme.hue(hue.name).expect("a known hue");
        for (step, color) in HUE_STEPS.iter().zip(steps) {
            writeln!(
                out,
                "            primitive::COLOR_{}_{step}: Color = hex(\"{}\");",
                hue.name.to_uppercase(),
                hex(color)
            )
            .expect("writing to a String never fails");
        }
        writeln!(
            out,
            "            primitive::COLOR_{}_SOURCE: Color = hex(\"{}\");",
            hue.name.to_uppercase(),
            hex(steps[8])
        )
        .expect("writing to a String never fails");
    }
    out
}

/// Replaces the lines between the generated markers of `path` with `lines`.
fn replace_generated(path: &Path, lines: &str) {
    let text = std::fs::read_to_string(path)
        .expect("a source file")
        .replace("\r\n", "\n");
    let start = text.find(GENERATED).expect("the start marker");
    let start = text[start..]
        .find('\n')
        .map(|end| start + end + 1)
        .expect("a line end");
    let end = text.find(END).expect("the end marker");
    let end = text[..end].rfind('\n').map_or(end, |line| line + 1);
    let written = format!("{}{lines}{}", &text[..start], &text[end..]);
    std::fs::write(path, written).expect("writable sources");
}

/// The palettes of the theme differ from the base theme's.
fn changes_palettes(theme: &ThemePalettes, base: &ThemePalettes) -> bool {
    theme.neutral() != base.neutral()
        || HUES
            .iter()
            .any(|hue| theme.hue(hue.name) != base.hue(hue.name))
}

#[test]
fn every_palette_step_keeps_its_contrast_in_every_theme() {
    let base = &THEMES[0];
    assert_eq!(
        base.theme,
        KOEBI.base_theme().key(),
        "the base theme comes first"
    );
    if std::env::var_os("KOEBI_BLESS").is_some() {
        std::fs::write(root().join("src/primitive/palette.rs"), palette_table(base))
            .expect("writable sources");
        replace_generated(
            &root().join("src/primitive/neutral.rs"),
            &gray_definitions(base),
        );
        for theme in &THEMES[1..] {
            if changes_palettes(theme, base) {
                let file = root().join(format!("src/themes/{}.rs", theme.theme.replace('-', "_")));
                replace_generated(&file, &theme_values(theme));
            }
        }
        return;
    }
    let mut design = DesignSystem::new(&KOEBI).expect("Koebi's schema is valid");
    for theme in &THEMES {
        let id = design
            .find_theme(theme.theme)
            .unwrap_or_else(|| panic!("no theme {}", theme.theme));
        design.set_active_theme(id).unwrap();
        let get = |path: String| -> Color {
            let token = design.find(&format!("primitive.{path}")).expect(&path);
            match design.value(token) {
                Some(koebi_design::value::Value::Color(color)) => *color,
                other => panic!("{path}: {other:?}"),
            }
        };
        let background = get("color.gray.50".to_owned());
        assert_eq!(background, theme.background(), "{}: gray.50", theme.theme);
        let max = Color::WHITE
            .contrast_ratio(background)
            .max(Color::BLACK.contrast_ratio(background));
        let check = |path: String, target: f32, fill: bool| {
            let color = get(path.clone());
            let ratio = color.contrast_ratio(background);
            let within = (ratio - target).abs() <= target * TOLERANCE
                // Out of reach: as far as the scale goes.
                || (target > max && ratio >= max * (1.0 - TOLERANCE) - 0.5)
                // A fill of a dark theme darkened for white content.
                || (fill
                    && theme.scheme == Scheme::Dark
                    && ratio < target
                    && Color::WHITE.contrast_ratio(color) >= 4.5);
            assert!(
                within,
                "{}: {path} at {ratio:.2}:1, its step asks {target}:1",
                theme.theme
            );
        };
        for (index, step) in NEUTRAL_STEPS.iter().enumerate().skip(2) {
            let fill = index <= LAST_NEUTRAL_FILL;
            check(
                format!("color.gray.{step}"),
                theme.neutral_contrasts[index],
                fill,
            );
        }
        for hue in HUES {
            for (index, (step, target)) in HUE_STEPS.iter().zip(theme.hue_contrasts()).enumerate() {
                check(
                    format!("color.{}.{step}", hue.name),
                    target,
                    index <= LAST_HUE_FILL,
                );
            }
        }
    }
}

#[test]
fn a_role_made_from_a_color_changes_its_family_and_resets() {
    use koebi_tokens::palettes::{Family, editable, is_seeded, reset, seed, source};
    use koebi_tokens::{component, semantic};
    let mut design = DesignSystem::new(&KOEBI).expect("Koebi's schema is valid");
    let theme = design.active_theme();
    let accent = editable().next().expect("the accent first");
    assert_eq!((accent.key, accent.family), ("accent", Family::Role));
    let before = design.get(component::BUTTON_ACCENT_BACKGROUND_COLOR_DEFAULT);
    assert!(!is_seeded(&design, theme, &accent));
    let orange = Color::from_hex(0xFF_88_00);
    seed(&mut design, theme, &accent, orange).unwrap();
    assert!(is_seeded(&design, theme, &accent));
    assert_eq!(source(&design, theme, &accent), Some(orange));
    // The button's fill is the orange itself (ADR 0027), far enough from the dark background,
    // and its content turns dark to read on it.
    let fill = design.get(component::BUTTON_ACCENT_BACKGROUND_COLOR_DEFAULT);
    assert_ne!(fill, before);
    assert_eq!(fill, design.get(semantic::ACCENT_COLOR_900));
    assert_eq!(fill.to_rgba8(), orange.to_rgba8());
    let content = design.get(component::BUTTON_ACCENT_LABEL_COLOR_DEFAULT);
    assert!(content.contrast_ratio(fill) >= 4.5, "{content} on {fill}");
    reset(&mut design, theme, &accent).unwrap();
    assert!(!is_seeded(&design, theme, &accent));
    assert_eq!(
        design.get(component::BUTTON_ACCENT_BACKGROUND_COLOR_DEFAULT),
        before
    );
}

#[test]
fn a_chosen_background_is_the_window_s_background_and_the_theme_follows() {
    use koebi_tokens::palettes::{Family, editable, reset, seed};
    use koebi_tokens::semantic;
    let mut design = DesignSystem::new(&KOEBI).expect("Koebi's schema is valid");
    let theme = design.active_theme();
    let neutral = editable()
        .find(|palette| palette.family == Family::Neutral)
        .expect("the neutral palette");
    let base = design.get(semantic::BACKGROUND_BASE_DEFAULT);
    let green = Color::from_hex(0x1E_3A_1C);
    seed(&mut design, theme, &neutral, green).unwrap();
    let background = design.get(semantic::BACKGROUND_BASE_DEFAULT);
    assert_eq!(
        background.to_rgba8(),
        green.to_rgba8(),
        "the chosen color itself"
    );
    // Text, borders and fills keep their contrasts with it: every palette was made again.
    let ratio = |token: koebi_design::Token<
        koebi_design::kind::Color,
        koebi_design::tier::Semantic,
    >| { design.get(token).contrast_ratio(background) };
    assert!(ratio(semantic::TEXT_COLOR_PRIMARY_DEFAULT) >= 7.0);
    assert!(ratio(semantic::TEXT_COLOR_SECONDARY_DEFAULT) >= 4.5);
    assert!(ratio(semantic::BACKGROUND_ACCENT_DEFAULT) >= 3.0);
    assert!(ratio(semantic::BACKGROUND_NEGATIVE_DEFAULT) >= 3.0);
    // Choosing it again changes nothing; a reset gives the theme back, with no override left.
    let revision = design.revision();
    seed(&mut design, theme, &neutral, green).unwrap();
    assert_eq!(design.get(semantic::BACKGROUND_BASE_DEFAULT), background);
    assert!(design.revision() >= revision);
    reset(&mut design, theme, &neutral).unwrap();
    assert_eq!(design.get(semantic::BACKGROUND_BASE_DEFAULT), base);
    assert_eq!(
        design
            .overrides(koebi_design::Scope::Theme(theme))
            .unwrap()
            .count(),
        0
    );
}

#[test]
fn every_palette_of_the_settings_has_its_tokens() {
    let design = DesignSystem::new(&KOEBI).expect("Koebi's schema is valid");
    let palettes: Vec<_> = koebi_tokens::palettes::editable().collect();
    assert_eq!(palettes.len(), 5 + 1 + 18);
    for palette in palettes {
        let source = design.find(&palette.source_path());
        assert!(source.is_some(), "{}", palette.key);
        let steps: Vec<_> = palette
            .step_paths()
            .iter()
            .map(|path| design.find(path).unwrap_or_else(|| panic!("{path}")))
            .collect();
        // The tokens found once, for the frames that show the palette, are the same.
        let tokens = palette.tokens(&design).expect("every token of the palette");
        assert_eq!(Some(tokens.source), source, "{}", palette.key);
        assert_eq!(tokens.steps.as_slice(), steps.as_slice(), "{}", palette.key);
        let theme = design.active_theme();
        assert_eq!(
            tokens.source(&design, theme),
            koebi_tokens::palettes::source(&design, theme, &palette)
        );
    }
}

#[test]
fn a_palette_made_again_from_its_own_source_changes_nothing() {
    // Choosing the color a palette already comes from leaves nothing to bring back: no
    // override of its source or its steps remains, in any theme.
    let mut design = DesignSystem::new(&KOEBI).unwrap();
    let themes: Vec<_> = design.themes().map(|(theme, _)| theme).collect();
    for theme in themes {
        for palette in koebi_tokens::palettes::editable() {
            let Some(source) = koebi_tokens::palettes::source(&design, theme, &palette) else {
                continue;
            };
            koebi_tokens::palettes::seed(&mut design, theme, &palette, source).unwrap();
            assert!(
                !koebi_tokens::palettes::is_seeded(&design, theme, &palette),
                "{} in {theme:?}",
                palette.key
            );
        }
        let left = design
            .overrides(koebi_design::Scope::Theme(theme))
            .unwrap()
            .count();
        assert_eq!(left, 0, "overrides left in {theme:?}");
    }
}

#[test]
fn a_palette_made_for_a_theme_shows_through_global_overrides_of_its_steps() {
    // Regression test for #243: global overrides of the accent's steps, as the gallery's editor
    // left them, hid the palette the settings made for the theme everywhere but step 900.
    use koebi_design::Scope;
    use koebi_design::value::{Definition, Value};
    use koebi_tokens::palettes;
    let mut design = DesignSystem::new(&KOEBI).unwrap();
    let theme = design.active_theme();
    let accent = palettes::editable()
        .find(|palette| palette.key == "accent")
        .unwrap();
    let steps: Vec<_> = accent
        .step_paths()
        .iter()
        .map(|path| design.find(path).unwrap())
        .collect();
    let pinned = Definition::Value(Value::Color(Color::from_hex(0x12_34_56)));
    for &step in &steps[..4] {
        design
            .set_override(Scope::Global, step, pinned.clone())
            .unwrap();
    }
    // Changed by global overrides alone: there is something to reset.
    assert!(palettes::is_changed(&design, theme, &accent));
    palettes::seed(&mut design, theme, &accent, Color::from_hex(0xD0_40_80)).unwrap();
    for &step in &steps {
        assert!(design.override_of(Scope::Global, step).is_none());
        let made = design.override_of(Scope::Theme(theme), step).cloned();
        assert_eq!(
            made.map(|made| match made {
                Definition::Value(value) => Some(value),
                Definition::Alias(_) => None,
            }),
            Some(design.value(step).cloned())
        );
    }
    // A reset clears both layers.
    design
        .set_override(Scope::Global, steps[0], pinned)
        .unwrap();
    palettes::reset(&mut design, theme, &accent).unwrap();
    assert!(!palettes::is_changed(&design, theme, &accent));
}
