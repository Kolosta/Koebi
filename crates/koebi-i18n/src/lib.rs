//! Koebi's translations: the catalogs of `locales/`, compiled into the binary, and the functions
//! that look messages up in the language chosen.
//!
//! English is the source language: the sources hold every message in English, and a message a
//! catalog does not translate shows in English. Each other language is a PO file
//! (`locales/fr.po`), the format of GNU gettext that translation tools read and write; the
//! template `locales/koebi.pot` lists every message, and `cargo xtask i18n` keeps both in step
//! with the sources (`docs/development/translation.md`).
//!
//! The build script reads the catalogs, checks them (plural forms, placeholders, the language
//! named in the header) and turns them into static tables sorted by message: a lookup is a
//! binary search, without allocation or lock. Fuzzy and empty translations are left out.
//!
//! ```
//! use koebi_i18n::{fill, tr, trn};
//!
//! assert_eq!(tr("Open"), "Open"); // English until another language is chosen
//! let count = 3;
//! let label = fill(trn("{count} file", "{count} files", count), &[("count", &count)]);
//! assert_eq!(label, "3 files");
//! ```
//!
//! Messages are marked where they are written: [`tr`], [`trc`] (with a context that tells two
//! identical English messages apart), [`trn`] (with a count), and [`n_!`] (or [`nc_!`], in a
//! context) for text stored before it is shown (action labels in statics), looked up with [`tr`]
//! (or [`trc`]) where it shows.

pub mod catalog;
pub mod plural;
pub mod po;

use core::cell::Cell;
use core::fmt::Display;
use core::sync::atomic::{AtomicU64, AtomicUsize, Ordering};

/// A message of a catalog: its context (empty for none), its English text, its translations.
type Message = (&'static str, &'static str, &'static [&'static str]);

/// A language Koebi shows: English, or one with a catalog.
#[derive(Debug)]
pub struct Language {
    code: &'static str,
    name: &'static str,
    english_name: &'static str,
    translated: usize,
    total: usize,
    plural: &'static [plural::Op],
    messages: &'static [Message],
}

impl Language {
    /// Its code, as the catalog's file is named: `en`, `fr`, `ja`, `pt_BR`.
    pub const fn code(&self) -> &'static str {
        self.code
    }

    /// Its name in itself: `Français`, `日本語`.
    pub const fn name(&self) -> &'static str {
        self.name
    }

    /// Its name in English: `French`, `Japanese`.
    pub const fn english_name(&self) -> &'static str {
        self.english_name
    }

    /// How many of the messages of the sources it translates.
    pub const fn translated(&self) -> usize {
        self.translated
    }

    /// How many messages the sources hold.
    pub const fn total(&self) -> usize {
        self.total
    }

    /// The share of the messages it translates, from 0 to 1; 1 for English.
    pub fn completion(&self) -> f32 {
        if self.total == 0 {
            1.0
        } else {
            self.translated as f32 / self.total as f32
        }
    }

    /// The same as a whole percentage, rounded down so that 100 means complete.
    pub fn percent(&self) -> u32 {
        (self.translated * 100)
            .checked_div(self.total)
            .map_or(100, |percent| u32::try_from(percent).unwrap_or(100))
    }

    fn lookup(&self, context: &str, id: &str) -> Option<&'static [&'static str]> {
        self.messages
            .binary_search_by(|&(c, i, _)| (c, i).cmp(&(context, id)))
            .ok()
            .map(|index| self.messages[index].2)
    }

    fn form(&self, count: u64) -> usize {
        usize::try_from(plural::eval(self.plural, count)).unwrap_or(0)
    }
}

/// English's plural rule: `n != 1`.
const ENGLISH_PLURAL: &[plural::Op] = &[
    plural::Op::N,
    plural::Op::Number(1),
    plural::Op::Binary(plural::Binary::NotEqual),
];

// `LANGUAGES`: English first, then every catalog by code; generated by the build script.
include!(concat!(env!("OUT_DIR"), "/catalogs.rs"));

static ACTIVE: AtomicUsize = AtomicUsize::new(0);
static REVISION: AtomicU64 = AtomicU64::new(0);

std::thread_local! {
    /// The language of this thread alone, while [`with_language`] runs.
    static OVERRIDE: Cell<Option<usize>> = const { Cell::new(None) };
}

/// Every language, English first.
pub fn languages() -> &'static [Language] {
    LANGUAGES
}

/// English, the source language.
pub fn english() -> &'static Language {
    &LANGUAGES[0]
}

/// The language messages show in.
pub fn language() -> &'static Language {
    let index = OVERRIDE
        .with(Cell::get)
        .unwrap_or_else(|| ACTIVE.load(Ordering::Relaxed));
    LANGUAGES.get(index).unwrap_or(&LANGUAGES[0])
}

fn index_of(language: &'static Language) -> usize {
    LANGUAGES
        .iter()
        .position(|candidate| core::ptr::eq(candidate, language))
        .unwrap_or(0)
}

/// Runs `f` with messages in `language` on this thread only, then as before: tests and previews
/// show a language without changing the application's.
pub fn with_language<R>(language: &'static Language, f: impl FnOnce() -> R) -> R {
    /// Puts the thread's previous language back, even when `f` panics.
    struct Restore(Option<usize>);
    impl Drop for Restore {
        fn drop(&mut self) {
            OVERRIDE.with(|cell| cell.set(self.0));
        }
    }
    let _restore = Restore(OVERRIDE.with(|cell| cell.replace(Some(index_of(language)))));
    f()
}

/// The language of `code` (`fr`, `pt_BR`; `-` reads as `_`, case does not matter).
pub fn find(code: &str) -> Option<&'static Language> {
    LANGUAGES
        .iter()
        .find(|language| same_code(language.code, code))
}

fn same_code(a: &str, b: &str) -> bool {
    a.len() == b.len()
        && a.bytes().zip(b.bytes()).all(|(x, y)| {
            let normal = |c: u8| {
                if c == b'-' {
                    b'_'
                } else {
                    c.to_ascii_lowercase()
                }
            };
            normal(x) == normal(y)
        })
}

/// The first language of `preferred` (the system's, best first: `fr-FR`, `en-US`) that Koebi
/// shows: the exact one (`pt_BR`), else its language alone (`pt`).
pub fn matching<'a>(preferred: impl IntoIterator<Item = &'a str>) -> Option<&'static Language> {
    preferred.into_iter().find_map(|wanted| {
        find(wanted).or_else(|| {
            let base = wanted.split(['-', '_']).next()?;
            find(base)
        })
    })
}

/// Shows messages in `language` from now on; returns whether it changed.
pub fn set_language(language: &'static Language) -> bool {
    let index = index_of(language);
    let changed = ACTIVE.swap(index, Ordering::Relaxed) != index;
    if changed {
        REVISION.fetch_add(1, Ordering::Relaxed);
    }
    changed
}

/// A number that changes each time the language does: what is drawn from translated text
/// redraws when it differs from the one it was drawn with.
pub fn revision() -> u64 {
    REVISION.load(Ordering::Relaxed)
}

/// `id`, an English message, in the current language.
pub fn tr(id: &str) -> &str {
    trc("", id)
}

/// `id` in the current language, in `context`: the same English text may translate differently
/// in two places (`Open` a file, `Open` as the state of a panel).
pub fn trc<'a>(context: &str, id: &'a str) -> &'a str {
    language()
        .lookup(context, id)
        .and_then(|strings| strings.first().copied())
        .unwrap_or(id)
}

/// The form of `id` (singular) and `plural` (English plural) for `count`, in the current
/// language: fill its `{count}` with [`fill`].
pub fn trn<'a>(id: &'a str, plural: &'a str, count: u64) -> &'a str {
    trnc("", id, plural, count)
}

/// [`trn`] in `context`.
pub fn trnc<'a>(context: &str, id: &'a str, plural: &'a str, count: u64) -> &'a str {
    let language = language();
    if let Some(strings) = language.lookup(context, id)
        && let Some(&text) = strings.get(language.form(count))
    {
        return text;
    }
    if english().form(count) == 0 {
        id
    } else {
        plural
    }
}

/// `text` with each `{name}` replaced by the value of that name in `values`; `{{` and `}}` write
/// a brace, and a name without a value stays as it is.
pub fn fill(text: &str, values: &[(&str, &dyn Display)]) -> String {
    let mut out = String::with_capacity(text.len() + 16);
    fill_into(&mut out, text, values);
    out
}

/// [`fill`] into `out`, cleared first: a buffer kept from frame to frame allocates once.
pub fn fill_into(out: &mut String, text: &str, values: &[(&str, &dyn Display)]) {
    out.clear();
    // Writing to a `String` cannot fail.
    let _ = write_filled(out, text, values);
}

/// [`fill`] written to `out`, which may be a buffer on the stack: nothing is allocated.
///
/// # Errors
///
/// What `out` returns when it is full.
pub fn write_filled(
    out: &mut impl core::fmt::Write,
    text: &str,
    values: &[(&str, &dyn Display)],
) -> core::fmt::Result {
    let mut rest = text;
    while let Some(at) = rest.find(['{', '}']) {
        out.write_str(&rest[..at])?;
        let brace = rest.as_bytes()[at];
        let after = &rest[at + 1..];
        if after.as_bytes().first() == Some(&brace) {
            out.write_char(char::from(brace))?;
            rest = &after[1..];
            continue;
        }
        if brace == b'{'
            && let Some(end) = after.find('}')
            && let Some((_, value)) = values.iter().find(|(key, _)| *key == &after[..end])
        {
            write!(out, "{value}")?;
            rest = &after[end + 1..];
            continue;
        }
        out.write_char(char::from(brace))?;
        rest = after;
    }
    out.write_str(rest)
}

/// Marks an English message stored before it is shown (an action's label in a static), so that
/// `cargo xtask i18n extract` lists it; it is the text itself, translated with [`tr`] where it
/// shows. It is `N_` of GNU gettext.
#[macro_export]
macro_rules! n_ {
    ($text:literal) => {
        $text
    };
}

/// [`n_!`] in a context: the text itself, translated with [`trc`] and the same context where it
/// shows (`nc_!("key", "Delete")`, then `trc("key", name)`).
#[macro_export]
macro_rules! nc_ {
    ($context:literal, $text:literal) => {
        $text
    };
}

#[cfg(test)]
mod tests {
    use super::*;

    static SAMPLE: Language = Language {
        code: "xx",
        name: "Sample",
        english_name: "Sample",
        translated: 3,
        total: 4,
        // French's rule: one form up to 1.
        plural: &[
            plural::Op::N,
            plural::Op::Number(1),
            plural::Op::Binary(plural::Binary::Greater),
        ],
        messages: &[
            ("", "Open", &["Ouvrir"]),
            ("", "{count} file", &["{count} fichier", "{count} fichiers"]),
            ("state", "Open", &["Ouvert"]),
        ],
    };

    #[test]
    fn messages_are_found_by_context_and_text() {
        assert_eq!(SAMPLE.lookup("", "Open"), Some(&["Ouvrir"][..]));
        assert_eq!(SAMPLE.lookup("state", "Open"), Some(&["Ouvert"][..]));
        assert_eq!(SAMPLE.lookup("", "Close"), None);
        assert_eq!(SAMPLE.lookup("menu", "Open"), None);
        assert_eq!(SAMPLE.percent(), 75);
    }

    #[test]
    fn plural_forms_follow_the_language_rule() {
        assert_eq!(SAMPLE.form(0), 0);
        assert_eq!(SAMPLE.form(1), 0);
        assert_eq!(SAMPLE.form(2), 1);
        assert_eq!(english().form(0), 1);
        assert_eq!(english().form(1), 0);
    }

    #[test]
    fn fill_replaces_names_and_keeps_the_rest() {
        let n = 3;
        assert_eq!(
            fill("{n} of {total}", &[("n", &n), ("total", &10)]),
            "3 of 10"
        );
        assert_eq!(
            fill("{{n}} {n} {unknown} }", &[("n", &n)]),
            "{n} 3 {unknown} }"
        );
        assert_eq!(fill("{ open", &[]), "{ open");
        let mut out = String::from("old");
        fill_into(&mut out, "é{n}", &[("n", &"日本")]);
        assert_eq!(out, "é日本");
    }

    #[test]
    fn a_thread_may_show_another_language_for_a_while() {
        let other = languages().last().unwrap_or(english());
        let (inside, elsewhere) = with_language(other, || {
            let elsewhere = std::thread::spawn(|| OVERRIDE.with(Cell::get))
                .join()
                .unwrap();
            (language().code(), elsewhere)
        });
        assert_eq!(inside, other.code());
        // Another thread kept the application's language, and this one is back to it.
        assert_eq!(elsewhere, None);
        assert_eq!(OVERRIDE.with(Cell::get), None);
    }

    #[test]
    fn languages_are_matched_by_code_then_language() {
        assert_eq!(english().code(), "en");
        assert_eq!(find("EN").map(Language::code), Some("en"));
        assert_eq!(matching(["xx-YY", "en-US"]).map(Language::code), Some("en"));
        assert!(matching(["xx"]).is_none());
        assert!(same_code("pt-br", "pt_BR"));
        assert!(!same_code("pt", "pt_BR"));
    }

    #[test]
    fn english_is_the_source_and_untranslated_text_shows_as_written() {
        // Only this test changes the language: the others read catalogs directly.
        assert_eq!(tr("Never translated"), "Never translated");
        assert_eq!(trn("{count} item", "{count} items", 1), "{count} item");
        assert_eq!(trn("{count} item", "{count} items", 0), "{count} items");
        for each in languages() {
            set_language(each);
            assert_eq!(language().code(), each.code());
            assert_eq!(tr("Never translated"), "Never translated");
            assert!(each.percent() <= 100);
        }
        let before = revision();
        assert!(set_language(english()) || languages().len() == 1);
        assert!(!set_language(english()));
        assert!(revision() >= before);
    }
}
